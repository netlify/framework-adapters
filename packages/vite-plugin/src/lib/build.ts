import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { dirname, join, relative, resolve, sep } from 'node:path'
import { sep as posixSep } from 'node:path/posix'

import js from 'dedent'
import type { Plugin, ResolvedConfig, Rollup } from 'vite'

import { createLoggerFromViteLogger } from './logger.js'
import { version, name } from '../../package.json'
import type { BuildPluginOptions, BuildTarget } from './types.js'

export type { BuildPluginOptions }

const USER_SERVER_DIRECTORY = 'netlify/server'
const SERVER_ENTRY_BASENAMES = new Set(['index.js', 'index.mjs', 'index.ts', 'index.mts'])

const DEFAULT_DISPLAY_NAME = '@netlify/vite-plugin server handler'
const GENERATOR = `${name}@${version}`

// Marks generated files, so we only ever remove our own.
const GENERATED_FILE_MARKER = `// Generated by ${name}. Do not edit.`

interface TargetContext {
  entrypoint: string
  displayName: string
  excludedPaths: string[]
}

interface Target {
  file: string
  render: (context: TargetContext) => string
}

const TARGETS: Record<BuildTarget, Target> = {
  function: {
    file: '.netlify/v1/functions/server.mjs',
    render: ({ entrypoint, displayName, excludedPaths }) => js`
      ${GENERATED_FILE_MARKER}
      import serverEntrypoint from "${entrypoint}";

      if (typeof serverEntrypoint?.fetch !== "function") {
        console.error("The server entry point must have a default export with a property \`fetch: (req: Request) => Promise<Response>\`");
      }

      export default serverEntrypoint.fetch;

      export const config = {
        name: "${displayName}",
        generator: "${GENERATOR}",
        path: "/*",
        excludedPath: ${JSON.stringify(excludedPaths)},
        preferStatic: true,
      };
    `,
  },

  edge: {
    file: '.netlify/v1/edge-functions/server.mjs',
    // Edge functions have no `preferStatic`, so static paths are excluded, and
    // need `cache: "manual"` for the app's caching headers to apply.
    render: ({ entrypoint, displayName, excludedPaths }) => js`
      ${GENERATED_FILE_MARKER}
      import serverEntrypoint from "${entrypoint}";

      if (typeof serverEntrypoint?.fetch !== "function") {
        console.error("The server entry point must have a default export with a property \`fetch: (req: Request) => Promise<Response>\`");
      }

      export default (request) => serverEntrypoint.fetch(request);

      export const config = {
        name: "${displayName}",
        generator: "${GENERATOR}",
        path: "/*",
        excludedPath: ${JSON.stringify(excludedPaths)},
        cache: "manual",
      };
    `,
  },

  server: {
    file: '.netlify/v1/server/index.mjs',
    render: ({ entrypoint }) => js`
      ${GENERATED_FILE_MARKER}
      export { default } from "${entrypoint}";
    `,
  },
}

const toPosixPath = (path: string) => path.split(sep).join(posixSep)

const findServerEntries = async (root: string, directory: string): Promise<string[]> => {
  const files = await readdir(join(root, directory)).catch((): string[] => [])

  return files.filter((file) => SERVER_ENTRY_BASENAMES.has(file)).map((file) => `${directory}/${file}`)
}

// Versions before the marker only wrote the `generator` line.
const isGenerated = async (path: string) => {
  const contents = await readFile(path, 'utf8').catch(() => '')

  return contents.startsWith(GENERATED_FILE_MARKER) || contents.includes(`generator: "${name}@`)
}

// A project can have one server only.
const assertNoOtherServer = async (root: string) => {
  const generatedEntry = TARGETS.server.file
  const frameworkEntries = await findServerEntries(root, dirname(generatedEntry))
  const otherEntries = await findServerEntries(root, USER_SERVER_DIRECTORY)

  for (const entry of frameworkEntries) {
    if (entry !== generatedEntry || !(await isGenerated(join(root, entry)))) {
      otherEntries.push(entry)
    }
  }

  if (otherEntries.length !== 0) {
    throw new Error(
      `build.target is set to 'server', but this project already has a Netlify Server in ${otherEntries.join(', ')}. A project can have one server only, so remove it to deploy your app's server build as the server, or set build.target to 'function' or 'edge'.`,
    )
  }
}

// TODO(serhalp): In the future, support Remix/RR7 by allowing a custom `getServerEntrypoint`
// passed as a plugin opt.
const getServerEntrypoint = (bundle: Rollup.OutputBundle, outDir: string): string => {
  // Find the built server entry point file in the bundle.
  // NOTE: This assumes there is only one BUNDLE entry and that this is the SERVER request entry point. This is an
  // assumption that everyone in the Vite ecosystem seems to make and it holds for our supported frameworks.
  const entryChunks = Object.values(bundle).filter(
    (chunk): chunk is Rollup.OutputChunk => chunk.type === 'chunk' && chunk.isEntry,
  )
  if (entryChunks.length === 0) {
    throw new Error('Could not find entry chunk in bundle - aborting!')
  }
  if (entryChunks.length > 1) {
    throw new Error('Found multiple entry chunks, unable to resolve server entry point - aborting!')
  }
  return join(outDir, entryChunks[0].fileName)
}

const listFiles = async (directory: string): Promise<string[] | undefined> => {
  const entries = await readdir(directory, { recursive: true, withFileTypes: true }).catch(() => undefined)

  return entries
    ?.filter((entry) => entry.isFile())
    .map((entry) => toPosixPath(relative(directory, join(entry.parentPath, entry.name))))
}

// Every URL the CDN serves from the client build, including the extensionless
// paths of HTML files.
const getStaticPaths = async (config: ResolvedConfig): Promise<string[]> => {
  const base = new URL(config.base, 'http://localhost').pathname
  const client = config.environments.client.build
  const paths = new Set<string>()
  let files = await listFiles(resolve(config.root, client.outDir))

  // The client build hasn't run yet, so fall back to what it will contain.
  if (files === undefined) {
    paths.add(`${base}${toPosixPath(client.assetsDir)}/*`)
    files = config.publicDir ? await listFiles(config.publicDir) : undefined
  }

  for (const file of files ?? []) {
    paths.add(`${base}${file}`)

    if (file === 'index.html' || file.endsWith('/index.html')) {
      const path = `${base}${file.slice(0, -'index.html'.length)}`

      paths.add(path)

      if (path !== '/') {
        paths.add(path.slice(0, -1))
      }
    } else if (file.endsWith('.html')) {
      paths.add(`${base}${file.slice(0, -'.html'.length)}`)
    }
  }

  return [...paths].sort()
}

const removeOtherTargets = async (root: string, target: BuildTarget) => {
  for (const [otherTarget, { file }] of Object.entries(TARGETS)) {
    if (otherTarget === target) {
      continue
    }

    const path = join(root, file)

    if (await isGenerated(path)) {
      await rm(path)
    }
  }
}

export function createBuildPlugin(options: BuildPluginOptions = {}): Plugin {
  const target = options.target ?? 'function'
  let resolvedConfig: ResolvedConfig

  return {
    name: 'vite-plugin-netlify:build',
    apply: 'build',
    /** @see {@link https://vite.dev/guide/api-environment-plugins.html#per-environment-plugins} */
    applyToEnvironment({ name }) {
      // There is a backwards-compatible environment with the name `ssr`:
      // https://vite.dev/guide/api-environment-runtimes.html#creating-a-new-environment-factory.
      // Eventually, to support more advanced configurations, we'll change this condition
      // to `consumer === 'server'` and pass down request routing metadata.
      return name === 'ssr'
    },
    /** @see {@link https://vite.dev/guide/api-plugin.html#configresolved} */
    configResolved(config) {
      resolvedConfig = config
    },

    /** @see {@link https://rollupjs.org/plugin-development/#buildstart} */
    async buildStart() {
      if (target === 'server') {
        await assertNoOtherServer(resolvedConfig.root)
      }
    },

    /** @see {@link https://rollupjs.org/plugin-development/#writebundle} */
    async writeBundle(_, bundle) {
      const { root } = resolvedConfig
      const { file, render } = TARGETS[target]
      const outputPath = join(root, file)
      const outDir = resolve(root, this.environment.config.build.outDir)
      const serverEntrypoint = getServerEntrypoint(bundle, outDir)
      let entrypoint = toPosixPath(relative(dirname(outputPath), serverEntrypoint))

      if (!entrypoint.startsWith('.')) {
        entrypoint = `./${entrypoint}`
      }

      await removeOtherTargets(root, target)
      await mkdir(dirname(outputPath), { recursive: true })
      await writeFile(
        outputPath,
        render({
          entrypoint,
          displayName: options.displayName ?? DEFAULT_DISPLAY_NAME,
          excludedPaths: [
            // Netlify's own routes, such as `/.netlify/images`.
            '/.netlify/*',
            ...(target === 'edge' ? await getStaticPaths(resolvedConfig) : []),
          ],
        }),
      )

      createLoggerFromViteLogger(resolvedConfig.logger).log(`✓ Wrote SSR entry point to ${file}\n`)
    },
  }
}
